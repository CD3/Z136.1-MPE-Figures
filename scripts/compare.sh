set -u
rm -rf build*

function usage {
cat << EOF
Usage: $0 [-h] [-v] [path/to/goldenimage/snapshot] [path/to/new/snapshot]

Compare two sets of figure snapshots (a set of eps and pdf files generated by running:

$ bash make-figures.sh eps pdf

This script can be used while working on script updates to make sure only expected changes
in apperance are introduced. For example, if a script is being refactored for some reason
that should not introduce changes in apperance, this script can be used to detect errors.

By default, this script compares the output of make-figures.sh (the build/ directory)
to a saved snapshot in the snapshots/ directory. The snapshot to compare the build directory
to can be given as an argument.

Example:

$ bash $0 snapshots/2023-11-28/

This script can also be used to see the differences between two different snapshots.
This is useful for seeing exactly which figures were changes between versions of
a standard. A visual PDF diff program needs to be installed (diffpdf or diff-pdf) needs
to be installed.

Example:

$ bash $0 -v snapshots/2023-11-28/ snapshots/2026-06-23-1/

EOF
}

VIEW_PDF_DIFFS=0

while getopts "hv" OPT
do
  case "${OPT}" in 
    v)
      VIEW_PDF_DIFFS=1
      ;;
    h)
      usage
      exit 1
      ;;
    \?)
      usage
      exit 1
      ;;
  esac
done
shift $((OPTIND-1))


GOLDEN_SNAPSHOT=${1:-"snapshots/2026-06-23-1/"}
NEW_SNAPSHOT=${2:-"build"}

if [ ! -d "${GOLDEN_SNAPSHOT}" ]
then
  printf "Golden snapshot directory '${GOLDEN_SNAPSHOT}' does not exist.\n"
  printf "This should be a directory containing EPS and PDF images of the figures to compare the output of the current scripts to.\n"
  exit 1
fi

if [ "${NEW_SNAPSHOT}" = "build" ]
then

printf "Running new bash script with eps and pdf arguments\n"
bash make-figures.sh eps pdf > /dev/null 2>&1


printf "Removing creation date and title lines from post script files.\n"
sed -i "/%%CreationDate/d;/%%Title/d;/\/CreationDate/d;/\/Title/d" build*/eps/*

fi


printf "Running diff on two snapshots directories\n"
printf "  Golden Snapshot: %b\n" "${GOLDEN_SNAPSHOT}"
printf "     New Snapshot: %b\n" "${NEW_SNAPSHOT}"
diff -r "${NEW_SNAPSHOT}/eps" "${GOLDEN_SNAPSHOT}/eps" && printf "EPS Images are IDENTICAL!\n"

DIFFPDF=$(which comparepdf || which diff-pdf || echo "")
if [ -z "${DIFFPDF}" ]
then
  printf "Can't diff PDF files, could not find 'diff-pdf' or 'diffpdf'. You can install it with 'apt install diff-pdf-wx' or 'apt install diffpdf'.\n"
  exit 1
fi
DIFFPDF_OPTS=""
if [ $(basename ${DIFFPDF}) = "comparepdf" ]
then
  DIFFPDF_OPTS="-ca"
fi

DIFFERENCES=""
IFS=$'\n\t'
for LINE in $(diff -r "${NEW_SNAPSHOT}/pdf" "${GOLDEN_SNAPSHOT}/pdf")
do
  # Binary files are different. Use a PDF diffing tool to make sure.
  FILE=$(echo ${LINE} | sed "s|Binary files.*pdf/||;s| .*||")

  "${DIFFPDF}" ${DIFFPDF_OPTS} "${NEW_SNAPSHOT}/pdf/${FILE}" "${GOLDEN_SNAPSHOT}/pdf/${FILE}"
  if [ "$?" -ne 0 ]
  then
    DIFFERENCES="${DIFFERENCES}\n${LINE}"
  fi
done
if [ -n "${DIFFERENCES}" ]
then
  printf "${DIFFERENCES}\n"
  printf "You can use 'diffpdf -a file1.pdf file2.pdf' or 'diff-pdf --view file1.pdf file2.pdf' to see the differences.\n"

  if [ "${VIEW_PDF_DIFFS}" -ne 0 ]
  then
    GRAPHIC_DIFFPDF=$(which diffpdf || which diff-pdf || echo "")
    DIFFPDF_OPTS=""
    if [ $(basename ${DIFFPDF}) = "diffpdf" ]
    then
      DIFFPDF_OPTS="-a"
    fi
    if [ $(basename ${DIFFPDF}) = "diff-pdf" ]
    then
      DIFFPDF_OPTS="--view"
    fi

    for LINE in "${DIFFERENCES}"
    do
      FILE=$(echo ${LINE} | sed "s|.*Binary files.*pdf/||;s| .*||")
      "${GRAPHIC_DIFFPDF}" ${DIFFPDF_OPTS} "${NEW_SNAPSHOT}/pdf/${FILE}" "${GOLDEN_SNAPSHOT}/pdf/${FILE}"
    done
  fi

else
  printf "PDF Images are IDENTICAL! (or at least appear to be)\n"
fi
